-- Ensure unique constraint on categories.slug
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'categories_slug_key'
    ) THEN
        ALTER TABLE public.categories ADD CONSTRAINT categories_slug_key UNIQUE (slug);
    END IF;
EXCEPTION
    WHEN OTHERS THEN NULL;
END $$;

-- ==============================================================================
-- 3. INDEXES FOR PERFORMANCE
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_projects_category_id ON public.projects(category_id);
CREATE INDEX IF NOT EXISTS idx_submissions_created_at ON public.submissions(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_submissions_status ON public.submissions(status);
CREATE INDEX IF NOT EXISTS idx_about_gallery_order ON public.about_gallery(display_order ASC);

-- ==============================================================================
-- 4. ROW LEVEL SECURITY (RLS) & CLEAN POLICY CREATION
-- ==============================================================================
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.about_gallery ENABLE ROW LEVEL SECURITY;

-- Drop old policies to avoid duplicate errors
DROP POLICY IF EXISTS "Public can view categories" ON public.categories;
DROP POLICY IF EXISTS "Full access to categories" ON public.categories;
DROP POLICY IF EXISTS "Public can view projects" ON public.projects;
DROP POLICY IF EXISTS "Full access to projects" ON public.projects;
DROP POLICY IF EXISTS "Public can insert submissions" ON public.submissions;
DROP POLICY IF EXISTS "Full access to submissions" ON public.submissions;
DROP POLICY IF EXISTS "Public can view gallery" ON public.about_gallery;
DROP POLICY IF EXISTS "Full access to gallery" ON public.about_gallery;

-- Re-create clean permissive policies
CREATE POLICY "Public can view categories" ON public.categories FOR SELECT USING (true);
CREATE POLICY "Full access to categories" ON public.categories FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Public can view projects" ON public.projects FOR SELECT USING (true);
CREATE POLICY "Full access to projects" ON public.projects FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Public can insert submissions" ON public.submissions FOR INSERT WITH CHECK (true);
CREATE POLICY "Full access to submissions" ON public.submissions FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Public can view gallery" ON public.about_gallery FOR SELECT USING (true);
CREATE POLICY "Full access to gallery" ON public.about_gallery FOR ALL USING (true) WITH CHECK (true);

