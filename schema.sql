-- ==============================================================================
-- SOR CONNECT - SUPABASE / POSTGRESQL DATABASE SCHEMA & MIGRATION SCRIPT
-- ==============================================================================
-- This script is 100% idempotent: it safely creates or updates tables, adds
-- missing columns (e.g. description), drops/re-creates policies cleanly,
-- and inserts initial data without throwing errors on existing databases.
-- ==============================================================================

-- 1. CREATE TABLES (IF NOT EXIST)
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client TEXT NOT NULL,
    location TEXT NOT NULL,
    capacity TEXT NOT NULL,
    sector_or_type TEXT,
    category_id BIGINT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    whatsapp TEXT,
    monthly_bill TEXT,
    pincode TEXT,
    note TEXT,
    status TEXT DEFAULT 'New',
    subject TEXT DEFAULT 'Solar Inquiry',
    source_url TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.about_gallery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    subtitle TEXT,
    badge TEXT DEFAULT 'Field Showcase',
    description TEXT,
    location TEXT,
    image TEXT NOT NULL,
    display_order INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

