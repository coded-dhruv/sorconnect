-- ==============================================================================
-- A. IF YOU ALREADY CREATED THE TABLE PREVIOUSLY:
-- Run this quick snippet to make date, venue, city, category, status optional:
-- ==============================================================================
DO $$
BEGIN
    IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'events') THEN
        ALTER TABLE public.events ALTER COLUMN event_date DROP NOT NULL;
        ALTER TABLE public.events ALTER COLUMN venue DROP NOT NULL;
        ALTER TABLE public.events ALTER COLUMN city DROP NOT NULL;
        ALTER TABLE public.events ALTER COLUMN category DROP NOT NULL;
        ALTER TABLE public.events ALTER COLUMN status DROP NOT NULL;
    END IF;
END $$;

-- ==============================================================================
-- B. FRESH TABLE CREATION (Required: title, summary, image_url. Everything else optional)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,                                 -- REQUIRED
    slug TEXT UNIQUE,
    summary TEXT NOT NULL,                               -- REQUIRED
    image_url TEXT NOT NULL,                             -- REQUIRED (Cover photo)
    event_date DATE,                                     -- Optional
    end_date DATE,                                       -- Optional
    time_schedule TEXT,                                  -- Optional
    venue TEXT,                                          -- Optional
    city TEXT,                                           -- Optional
    description TEXT,                                    -- Optional
    organizer TEXT DEFAULT 'Sor Connect',                -- Optional
    registration_url TEXT,                               -- Optional
    featured BOOLEAN DEFAULT FALSE,                      -- Optional
    display_order INT DEFAULT 0,                         -- Optional
    category TEXT DEFAULT NULL,                          -- Deprecated / Optional
    status TEXT DEFAULT NULL,                            -- Deprecated / Optional
    booth_info TEXT DEFAULT NULL,                        -- Deprecated / Optional
    gallery_urls TEXT[] DEFAULT '{}',                    -- Deprecated / Optional
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;

-- Define Access Policies for Public Reading and Admin Anonymous Key Writing
DROP POLICY IF EXISTS "Public can view published events" ON public.events;
CREATE POLICY "Public can view published events"
ON public.events
FOR SELECT
USING (true);

DROP POLICY IF EXISTS "Admin anon insert events" ON public.events;
CREATE POLICY "Admin anon insert events"
ON public.events
FOR INSERT
WITH CHECK (true);

DROP POLICY IF EXISTS "Admin anon update events" ON public.events;
CREATE POLICY "Admin anon update events"
ON public.events
FOR UPDATE
USING (true);

DROP POLICY IF EXISTS "Admin anon delete events" ON public.events;
CREATE POLICY "Admin anon delete events"
ON public.events
FOR DELETE
USING (true);

-- Create Performance Indexes
CREATE INDEX IF NOT EXISTS idx_events_date ON public.events (event_date DESC);
CREATE INDEX IF NOT EXISTS idx_events_featured ON public.events (featured);
