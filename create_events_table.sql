-- 1. Create the `events` table
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    slug TEXT UNIQUE,
    category TEXT NOT NULL DEFAULT 'Exhibition', -- 'Exhibition', 'Conference', 'Award & Gala', 'Inauguration', 'Workshop', 'Community & CSR'
    event_date DATE NOT NULL,
    end_date DATE,
    time_schedule TEXT, -- e.g. '10:00 AM – 6:00 PM IST'
    venue TEXT NOT NULL,
    city TEXT DEFAULT 'Jaipur',
    status TEXT NOT NULL DEFAULT 'upcoming', -- 'upcoming', 'ongoing', 'completed'
    booth_info TEXT, -- e.g. 'Hall 3, Booth B-114'
    summary TEXT NOT NULL,
    description TEXT,
    image_url TEXT NOT NULL,
    gallery_urls TEXT[] DEFAULT '{}',
    organizer TEXT DEFAULT 'Sor Connect',
    registration_url TEXT,
    featured BOOLEAN DEFAULT FALSE,
    display_order INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;

-- 3. Define Access Policies for Public Reading and Admin Anonymous Key Writing
DROP POLICY IF EXISTS "Public can view published events" ON public.events;
CREATE POLICY "Public can view published events"
ON public.events
FOR SELECT
USING (true);

DROP POLICY IF EXISTS "Admin anon insert events" ON public.events;
CREATE POLICY "Admin anon insert events"
ON public.events
FOR INSERT
WITH CHECK (true);

DROP POLICY IF EXISTS "Admin anon update events" ON public.events;
CREATE POLICY "Admin anon update events"
ON public.events
FOR UPDATE
USING (true);

DROP POLICY IF EXISTS "Admin anon delete events" ON public.events;
CREATE POLICY "Admin anon delete events"
ON public.events
FOR DELETE
USING (true);

-- 4. Create Performance Indexes
CREATE INDEX IF NOT EXISTS idx_events_date ON public.events (event_date DESC);
CREATE INDEX IF NOT EXISTS idx_events_status ON public.events (status);
CREATE INDEX IF NOT EXISTS idx_events_category ON public.events (category);
CREATE INDEX IF NOT EXISTS idx_events_featured ON public.events (featured);

